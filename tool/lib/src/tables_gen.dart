import 'dart:io';

import 'package:path/path.dart' as p;
import 'package:pde_tool/src/repo.dart';

const tablesDir = 'packages/game_data/tables';
const tablesOut = 'packages/game_data/lib/src/tables.g.dart';

/// game_data는 dart:io를 못 쓰므로 JSON 테이블을 const 문자열로 심는다.
String generateTablesSource(Directory root) {
  final files = filesUnder(Directory(p.join(root.path, tablesDir)), extension: '.json').toList()
    ..sort((a, b) => a.path.compareTo(b.path));
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/gen_tables.dart — 직접 고치지 마세요.')
    ..writeln('// 원본: $tablesDir/*.json')
    ..writeln()
    ..writeln('/// 테이블 이름(파일명에서 .json 뺀 것) → JSON 원문.')
    ..writeln('const Map<String, String> rawTables = {');
  for (final f in files) {
    final name = p.basenameWithoutExtension(f.path);
    final json = f.readAsStringSync().replaceAll('\r\n', '\n').trimRight();
    if (json.contains("'''")) {
      throw FormatException("${f.path}에 ''' 가 있어 임베드할 수 없습니다.");
    }
    b
      ..writeln("  '$name': r'''")
      ..writeln(json)
      ..writeln("''',");
  }
  b.writeln('};');
  return b.toString();
}

/// 생성물이 원본 JSON과 맞는지 확인한다.
List<Violation> checkTablesFresh(Directory root) {
  final out = File(p.join(root.path, tablesOut));
  final expected = generateTablesSource(root);
  if (!out.existsSync() || out.readAsStringSync().replaceAll('\r\n', '\n') != expected) {
    return [
      const Violation(
        tablesOut,
        '테이블 JSON과 생성물이 다릅니다 — `dart run tool/gen_tables.dart`를 실행하세요',
      ),
    ];
  }
  return const [];
}
